import io
from html import escape as escape_xml
from datetime import datetime, timezone
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from sqlalchemy.orm import Session
from app.models.case import Case
from app.models.entity import Person, Phone, Vehicle, Document, Event
from app.models.relationship import Relationship
from app.services.similarity.case_similarity import find_cross_case_links, find_similar_cases
from app.services.graph.network_service import NetworkGraphService

def generate_case_pdf_report(case_id: int, db: Session) -> bytes:
    case = db.query(Case).filter(Case.id == case_id).first()
    if not case:
        raise ValueError(f"Case with ID {case_id} not found")

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40
    )

    styles = getSampleStyleSheet()
    
    # Custom Styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=22,
        textColor=colors.HexColor('#0F172A'),
        spaceAfter=10
    )
    
    h2_style = ParagraphStyle(
        'SectionH2',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        textColor=colors.HexColor('#1E293B'),
        spaceBefore=14,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'DocBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        textColor=colors.HexColor('#334155'),
        leading=14
    )

    disclaimer_style = ParagraphStyle(
        'Disclaimer',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        textColor=colors.HexColor('#991B1B'),
        backColor=colors.HexColor('#FEE2E2'),
        borderColor=colors.HexColor('#F87171'),
        borderWidth=1,
        borderPadding=8,
        spaceBefore=10,
        spaceAfter=15,
        leading=12
    )

    elements = []

    # Title & Header
    elements.append(Paragraph("CRIMEGRAPH AI — INVESTIGATION INTELLIGENCE REPORT", title_style))
    elements.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor('#0284C7'), spaceAfter=15))
    
    # Disclaimer
    elements.append(Paragraph(
        "MANDATORY LEGAL DISCLAIMER: This report is an analytical decision-support output generated by CrimeGraph AI. "
        "It does not establish criminal guilt, make legal accusations, or draw legal conclusions. All entities, linkages, "
        "and pattern scores represent analytical leads that MUST be independently verified by authorized investigators.",
        disclaimer_style
    ))

    # 1. Case Summary
    elements.append(Paragraph("1. Case Overview & Meta Summary", h2_style))
    case_data = [
        [Paragraph("<b>Case Number:</b>", body_style), Paragraph(escape_xml(str(case.case_number)), body_style)],
        [Paragraph("<b>Title:</b>", body_style), Paragraph(escape_xml(str(case.title)), body_style)],
        [Paragraph("<b>Case Type:</b>", body_style), Paragraph(escape_xml(str(case.case_type)), body_style)],
        [Paragraph("<b>Status:</b>", body_style), Paragraph(escape_xml(case.status.value if hasattr(case.status, 'value') else str(case.status)), body_style)],
        [Paragraph("<b>Description:</b>", body_style), Paragraph(escape_xml(str(case.description or "N/A")), body_style)],
        [Paragraph("<b>Generated On:</b>", body_style), Paragraph(datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"), body_style)]
    ]
    case_table = Table(case_data, colWidths=[120, 400])
    case_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#E2E8F0')),
        ('PADDING', (0,0), (-1,-1), 6),
    ]))
    elements.append(case_table)
    elements.append(Spacer(1, 15))

    # 2. Extracted Entities Summary
    elements.append(Paragraph("2. Key Extracted Entities", h2_style))
    relationships = db.query(Relationship).filter(Relationship.case_id == case_id).all()
    entity_types = set()
    entity_vals = []
    for r in relationships:
        entity_vals.append((r.source_entity_type, r.source_entity_id))
        entity_vals.append((r.target_entity_type, r.target_entity_id))
    
    unique_entities = list(set(entity_vals))
    
    if unique_entities:
        ent_rows = [[Paragraph("<b>Type</b>", body_style), Paragraph("<b>Entity Identifier / Value</b>", body_style)]]
        for etype, evalue in unique_entities[:20]:
            ent_rows.append([Paragraph(escape_xml(str(etype)), body_style), Paragraph(escape_xml(str(evalue)), body_style)])
        
        ent_table = Table(ent_rows, colWidths=[150, 370])
        ent_table.setStyle(TableStyle([
            ('HEADERBACKGROUND', (0,0), (-1,0), colors.HexColor('#E0F2FE')),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
            ('PADDING', (0,0), (-1,-1), 5),
        ]))
        elements.append(ent_table)
    else:
        elements.append(Paragraph("No entities linked to this case.", body_style))
    elements.append(Spacer(1, 15))

    # 3. Cross-Case Links
    elements.append(Paragraph("3. Cross-Case Intelligence Links", h2_style))
    cross_links = [cl for cl in find_cross_case_links(db) if cl["case_a_id"] == case_id or cl["case_b_id"] == case_id]
    if cross_links:
        cl_rows = [[Paragraph("<b>Target Case</b>", body_style), Paragraph("<b>Shared Entity</b>", body_style), Paragraph("<b>Confidence</b>", body_style), Paragraph("<b>Status</b>", body_style)]]
        for cl in cross_links:
            target_num = cl["case_b_number"] if cl["case_a_id"] == case_id else cl["case_a_number"]
            cl_rows.append([
                Paragraph(escape_xml(str(target_num)), body_style),
                Paragraph(f"{escape_xml(str(cl['shared_entity_type']))}: {escape_xml(str(cl['shared_entity_value']))}", body_style),
                Paragraph(f"{int(cl['confidence']*100)}%", body_style),
                Paragraph(escape_xml(str(cl["status"])), body_style)
            ])
        cl_table = Table(cl_rows, colWidths=[120, 180, 80, 140])
        cl_table.setStyle(TableStyle([
            ('HEADERBACKGROUND', (0,0), (-1,0), colors.HexColor('#FEF08A')),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#E2E8F0')),
            ('PADDING', (0,0), (-1,-1), 5),
        ]))
        elements.append(cl_table)
    else:
        elements.append(Paragraph("No cross-case entity overlaps detected for this case.", body_style))
    elements.append(Spacer(1, 15))

    # 4. Key Network Analytics
    elements.append(Paragraph("4. Network Centrality Lead Entities", h2_style))
    graph_svc = NetworkGraphService(db)
    top_entities = graph_svc.get_top_key_entities(limit=5)
    if top_entities:
        ke_rows = [[Paragraph("<b>Entity</b>", body_style), Paragraph("<b>Type</b>", body_style), Paragraph("<b>Connections</b>", body_style), Paragraph("<b>Degree Centrality</b>", body_style)]]
        for ke in top_entities:
            ke_rows.append([
                Paragraph(escape_xml(str(ke["entity_name"])), body_style),
                Paragraph(escape_xml(str(ke["entity_type"])), body_style),
                Paragraph(escape_xml(str(ke["connections_count"])), body_style),
                Paragraph(escape_xml(str(ke["degree_centrality"])), body_style)
            ])
        ke_table = Table(ke_rows, colWidths=[180, 100, 100, 140])
        ke_table.setStyle(TableStyle([
            ('HEADERBACKGROUND', (0,0), (-1,0), colors.HexColor('#E2E8F0')),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
            ('PADDING', (0,0), (-1,-1), 5),
        ]))
        elements.append(ke_table)

    elements.append(Spacer(1, 20))
    elements.append(Paragraph("End of CrimeGraph AI Intelligence Summary Report", ParagraphStyle('Footer', parent=styles['Normal'], fontName='Helvetica-Oblique', fontSize=9, textColor=colors.HexColor('#64748B'))))

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
